import { useState, useMemo } from "react";
import { motion, AnimatePresence } from "framer-motion";

export default function DayClosingModal({
  isOpen,
  onClose,
  hisaabData,
  storeName = "KiranaSync Store",
}) {
  const [actualCash, setActualCash] = useState("");
  const now = useMemo(() => new Date(), []);
  const dateStr = now.toLocaleDateString("en-IN", {
    weekday: "short",
    day: "2-digit",
    month: "short",
    year: "numeric",
  });
  const timeStr = now.toLocaleTimeString("en-IN", {
    hour: "2-digit",
    minute: "2-digit",
    hour12: true,
  });

  const expectedCash = useMemo(() => {
    return Number(hisaabData?.CashCollected || 0);
  }, [hisaabData]);

  const cashDiff = useMemo(() => {
    if (!actualCash || isNaN(actualCash)) return null;
    return Number(actualCash) - expectedCash;
  }, [actualCash, expectedCash]);

  const shareSummaryWhatsApp = () => {
    const summary = [
      ` *DUKAN BANDI / DAY CLOSING REPORT*`,
      `Store: ${storeName}`,
      `Date: ${dateStr} at ${timeStr}`,
      `────────────────────────────`,
      ` *Total Sales Today:* ₹${Number(hisaabData?.TotalRevenue || 0).toLocaleString("en-IN")}`,
      ` *Cash Sales:* ₹${Number(hisaabData?.CashSalesTotal || 0).toLocaleString("en-IN")}`,
      ` *Udhaar Given:* ₹${Number(hisaabData?.UdhaarSalesTotal || 0).toLocaleString("en-IN")}`,
      ` *Udhaar Recovered:* ₹${Number(hisaabData?.RepaymentsTotal || 0).toLocaleString("en-IN")}`,
      `────────────────────────────`,
      ` *Expected Drawer Cash:* ₹${expectedCash.toLocaleString("en-IN")}`,
      actualCash !== "" ? ` *Actual Cash Counted:* ₹${Number(actualCash).toLocaleString("en-IN")}` : "",
      cashDiff !== null ? ` *Variance:* ${cashDiff >= 0 ? "+" : ""}₹${cashDiff.toFixed(2)}` : "",
      `────────────────────────────`,
      ` *Total Outstanding Khata Debt:* ₹${Number(hisaabData?.TotalOutstandingDebt || 0).toLocaleString("en-IN")}`,
      `────────────────────────────`,
      `Generated by KiranaSync Retail POS`,
    ].filter(Boolean).join("\\n");

    window.open(`https://wa.me/?text=${encodeURIComponent(summary)}`, "_blank");
  };

  const handlePrint = () => {
    window.print();
  };

  if (!isOpen) return null;

  return (
    <AnimatePresence>
      <div className="fixed inset-0 z-[100] flex items-center justify-center p-4 pointer-events-auto">
        <motion.div
          className="absolute inset-0 bg-black/70 backdrop-blur-sm cursor-pointer"
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          exit={{ opacity: 0 }}
          onClick={onClose}
        />

        <motion.div
          className="relative w-full max-w-lg bg-[#FAF7F2] rounded-2xl shadow-2xl border-2 border-[#991B1B] overflow-hidden z-10 font-mono text-stone-800"
          initial={{ scale: 0.93, opacity: 0, y: 20 }}
          animate={{ scale: 1, opacity: 1, y: 0 }}
          exit={{ scale: 0.93, opacity: 0, y: 20 }}
        >
          {/* Header */}
          <div className="px-5 py-4 bg-[#FFFDF9] border-b border-[#E2D9C8] flex justify-between items-center">
            <div>
              <h3 className="text-base font-black text-stone-900 uppercase tracking-wider flex items-center gap-2">
                <span></span>
                <span>Day-End Closing (दुकान बंदी)</span>
              </h3>
              <p className="text-xs text-stone-500 mt-0.5">
                {dateStr} · {timeStr}
              </p>
            </div>
            <button
              onClick={onClose}
              className="text-stone-400 hover:text-stone-900 text-2xl font-bold w-8 h-8 flex items-center justify-center rounded-lg hover:bg-stone-200 transition-all cursor-pointer"
            >
              &times;
            </button>
          </div>

          <div className="p-5 space-y-4 max-h-[75vh] overflow-y-auto custom-scrollbar">
            {/* Cash Drawer Reconciliation Box */}
            <div className="p-4 rounded-xl bg-white border border-[#D8CEBA] shadow-2xs space-y-3">
              <div className="flex justify-between items-center text-xs">
                <span className="font-bold text-stone-700 uppercase tracking-wide">
                  Expected Cash in Galla (Register)
                </span>
                <span className="font-bold text-lg text-emerald-800 tabular-nums">
                  ₹{expectedCash.toLocaleString("en-IN", { minimumFractionDigits: 2 })}
                </span>
              </div>

              <div className="border-t border-dashed border-stone-200" />

              <div className="flex items-center justify-between gap-3 text-xs">
                <label className="font-semibold text-stone-800">
                  Actual Physical Cash Counted:
                </label>
                <div className="flex items-center bg-[#FAF7F2] border border-[#D8CEBA] rounded-lg px-2.5 py-1.5 w-36">
                  <span className="text-stone-400 mr-1 font-bold">₹</span>
                  <input
                    type="number"
                    step="any"
                    placeholder="Counted cash"
                    value={actualCash}
                    onChange={(e) => setActualCash(e.target.value)}
                    className="w-full text-right font-bold font-mono text-stone-900 bg-transparent focus:outline-none"
                  />
                </div>
              </div>

              {cashDiff !== null && (
                <div
                  className={`p-2.5 rounded-lg text-xs font-semibold flex items-center justify-between ${
                    Math.abs(cashDiff) < 0.01
                      ? "bg-emerald-50 text-emerald-900 border border-emerald-300"
                      : cashDiff > 0
                      ? "bg-amber-50 text-amber-900 border border-amber-300"
                      : "bg-red-50 text-red-900 border border-red-300"
                  }`}
                >
                  <span>
                    {Math.abs(cashDiff) < 0.01
                      ? " Cash drawer matches expected amount exactly!"
                      : cashDiff > 0
                      ? "▲ Excess cash in drawer:"
                      : "▼ Shortage in drawer:"}
                  </span>
                  <span className="font-bold font-mono">
                    {cashDiff >= 0 ? "+" : ""}₹{cashDiff.toFixed(2)}
                  </span>
                </div>
              )}
            </div>

            {/* Sales & Udhaar Breakdown Grid */}
            <div className="grid grid-cols-2 gap-3 text-xs">
              <div className="p-3 bg-white rounded-xl border border-[#E2D9C8]">
                <span className="text-stone-500 block text-[11px] font-semibold uppercase">
                  Gross Sales Today
                </span>
                <span className="text-base font-bold text-stone-900 font-mono mt-0.5 block">
                  ₹{Number(hisaabData?.TotalRevenue || 0).toLocaleString("en-IN")}
                </span>
                <span className="text-[10px] text-stone-400">
                  Cash + Udhaar orders
                </span>
              </div>

              <div className="p-3 bg-white rounded-xl border border-[#E2D9C8]">
                <span className="text-stone-500 block text-[11px] font-semibold uppercase">
                  Cash Sales Volume
                </span>
                <span className="text-base font-bold text-emerald-800 font-mono mt-0.5 block">
                  ₹{Number(hisaabData?.CashSalesTotal || 0).toLocaleString("en-IN")}
                </span>
                <span className="text-[10px] text-stone-400">
                  {hisaabData?.CashSalesCount || 0} counter sale(s)
                </span>
              </div>

              <div className="p-3 bg-white rounded-xl border border-[#E2D9C8]">
                <span className="text-stone-500 block text-[11px] font-semibold uppercase">
                  Udhaar Given Today
                </span>
                <span className="text-base font-bold text-red-800 font-mono mt-0.5 block">
                  ₹{Number(hisaabData?.UdhaarSalesTotal || 0).toLocaleString("en-IN")}
                </span>
                <span className="text-[10px] text-stone-400">
                  {hisaabData?.UdhaarSalesCount || 0} credit order(s)
                </span>
              </div>

              <div className="p-3 bg-white rounded-xl border border-[#E2D9C8]">
                <span className="text-stone-500 block text-[11px] font-semibold uppercase">
                  Udhaar Recovered
                </span>
                <span className="text-base font-bold text-blue-800 font-mono mt-0.5 block">
                  ₹{Number(hisaabData?.RepaymentsTotal || 0).toLocaleString("en-IN")}
                </span>
                <span className="text-[10px] text-stone-400">
                  {hisaabData?.RepaymentsCount || 0} customer repayment(s)
                </span>
              </div>
            </div>

            {/* Total Outstanding Customer Debt Bar */}
            <div className="p-3 bg-stone-100/90 rounded-xl border border-[#D8CEBA] flex justify-between items-center text-xs">
              <div>
                <span className="font-bold text-stone-800 block">
                  Total Outstanding Khata Debt (All Customers)
                </span>
                <span className="text-[10px] text-stone-500">
                  Combined active balance pending collection
                </span>
              </div>
              <span className="text-base font-black text-red-900 font-mono">
                ₹{Number(hisaabData?.TotalOutstandingDebt || 0).toLocaleString("en-IN")}
              </span>
            </div>
          </div>

          {/* Action Buttons */}
          <div className="px-5 py-3.5 bg-[#FFFDF9] border-t border-[#E2D9C8] flex gap-2.5">
            <button
              onClick={handlePrint}
              className="flex-1 py-2.5 px-3 rounded-xl bg-stone-900 hover:bg-stone-800 text-white font-bold text-xs flex items-center justify-center gap-1.5 shadow-xs transition-all cursor-pointer"
            >
              <span></span>
              <span>Print Closing Slip</span>
            </button>
            <button
              onClick={shareSummaryWhatsApp}
              className="flex-1 py-2.5 px-3 rounded-xl bg-emerald-700 hover:bg-emerald-600 text-white font-bold text-xs flex items-center justify-center gap-1.5 shadow-xs transition-all cursor-pointer"
            >
              <span></span>
              <span>WhatsApp Report</span>
            </button>
            <button
              onClick={onClose}
              className="py-2.5 px-4 rounded-xl border border-[#D8CEBA] text-stone-700 hover:bg-stone-100 font-bold text-xs transition-all cursor-pointer"
            >
               Close
            </button>
          </div>
        </motion.div>
      </div>
    </AnimatePresence>
  );
}
